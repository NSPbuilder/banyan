import { constants } from 'node:fs'
import { access, cp, mkdir, mkdtemp, readFile, rename, rm, stat, writeFile } from 'node:fs/promises'
import { basename, join, relative, resolve, sep } from 'node:path'
import { spawn } from 'node:child_process'
import { ADDON_MODULES, BASE_MODULES, type AddonId, type ModuleExclusion, type ModuleManifest } from '../src/lib/module-contract'
import { addonCatalog } from './addon-catalog'
import { BASE, fileModule } from './module-map'

const catalog = new Map(addonCatalog.map(manifest => [manifest.id, manifest]))

export function selectedModules(selection: string): ModuleManifest[] {
  const value = selection.trim().toUpperCase()
  if (!value) throw new Error('Choose --modules base, all, or a comma-separated list of add-ons.')
  const requested = new Set(value === 'BASE' || value === 'NONE' ? [] : value === 'ALL' ? ADDON_MODULES : value.split(',').map(id => id.trim()))
  for (const id of requested) if (!catalog.has(id as AddonId)) throw new Error(`Unknown add-on ${id}. Available: ${ADDON_MODULES.join(', ')}.`)
  const ordered = ADDON_MODULES.filter(id => requested.has(id)).map(id => catalog.get(id)!)
  const visited = new Set<AddonId>()
  const visit = (manifest: ModuleManifest, stack: AddonId[]) => {
    if (stack.includes(manifest.id)) throw new Error(`Module dependency cycle: ${[...stack, manifest.id].join(' -> ')}.`)
    if (visited.has(manifest.id)) return
    for (const dependency of manifest.requires) {
      if (!requested.has(dependency)) throw new Error(`${manifest.id} requires ${dependency}. Include both in --modules.`)
      const required = catalog.get(dependency)
      if (!required) throw new Error(`${manifest.id} declares unknown dependency ${dependency}.`)
      visit(required, [...stack, manifest.id])
    }
    visited.add(manifest.id)
  }
  for (const manifest of ordered) visit(manifest, [])
  return ordered
}

const exists = (path: string) => access(path).then(() => true, () => false)
const sourcePath = (path: string) => path.replaceAll(sep, '/')

export function composition(selected: ModuleManifest[]) {
  const header = '// Generated by modules:assemble. Change the selection and assemble again.\n'
  const imports = selected.map(manifest => `import { manifest as ${manifest.id.toLowerCase()} } from '@/modules/${manifest.id.toLowerCase()}/manifest'`).join('\n')
  return {
    'catalog.ts': `${header}import type { ModuleManifest } from '@/lib/module-contract'\n${imports}\nexport const moduleManifests: readonly ModuleManifest[] = [${selected.map(manifest => manifest.id.toLowerCase()).join(', ')}]\n`,
    'selection.ts': `${header}export const selectedAddons = ${JSON.stringify(selected.map(manifest => manifest.id))} as const\n`,
    'server.ts': `${header}import 'server-only'\nimport type { ModuleExtension } from '@/lib/module-extensions'\nexport const serverExtensions: Array<() => Promise<ModuleExtension>> = [\n${selected.filter(manifest => manifest.server).map(manifest => `  () => import('${manifest.server}').then(module => module.extension),`).join('\n')}\n]\n`,
    'settings.ts': `${header}import 'server-only'\nimport type { SettingsExtension } from '@/lib/settings-extensions'\nexport const settingsExtensions: Array<() => Promise<SettingsExtension>> = [\n${selected.filter(manifest => manifest.settings).map(manifest => `  () => import('${manifest.settings}').then(module => module.renderSettings),`).join('\n')}\n]\n`,
    'readings.ts': `${header}import type { StructuredReadingExtension } from '@/lib/structured-readings'\n${selected.filter(manifest => manifest.readings).map(manifest => `import { structuredReading as ${manifest.id.toLowerCase()} } from '${manifest.readings}'`).join('\n')}\nexport const structuredReadingExtensions: readonly StructuredReadingExtension[] = [${selected.filter(manifest => manifest.readings).map(manifest => manifest.id.toLowerCase()).join(', ')}]\n`,
  }
}

export async function assembleModules(options: { selection: string; output?: string; root?: string }) {
  const root = resolve(options.root ?? process.cwd()), selected = selectedModules(options.selection)
  const ids = new Set(selected.map(manifest => manifest.id))
  const key = selected.length === 0 ? 'base' : selected.length === ADDON_MODULES.length ? 'all' : selected.map(manifest => manifest.id.toLowerCase()).join('-')
  const output = resolve(options.output ?? join(root, 'build', 'assembled', key))
  const localOutput = relative(root, output)
  if (output === root || (!localOutput.startsWith('..' + sep) && localOutput !== '..' && !localOutput.startsWith('build' + sep))) {
    throw new Error('Place assembled outputs under build/ or outside this working repository.')
  }
  if (await exists(output)) throw new Error(`Output already exists: ${output}. Choose a new directory; existing files are never overwritten.`)
  for (const manifest of selected) for (const entry of [manifest.server, manifest.settings, manifest.readings]) {
    if (!entry) continue
    if (!entry.startsWith(`@/modules/${manifest.id.toLowerCase()}/`) || !await Promise.all(['.ts', '.tsx'].map(extension => exists(join(root, entry.replace('@/', 'src/')) + extension))).then(found => found.some(Boolean))) {
      throw new Error(`Module ${manifest.id} has an invalid entrypoint: ${entry}.`)
    }
  }
  await mkdir(resolve(output, '..'), { recursive: true })
  await mkdir(output)
  let sourceFiles = 0
  await cp(join(root, 'src'), join(output, 'src'), {
    recursive: true,
    filter: async path => {
      const directory = (await stat(path)).isDirectory()
      const owner = fileModule(sourcePath(relative(root, path)) + (directory ? '/__module__.ts' : ''))
      const include = BASE.has(owner) || ids.has(owner as AddonId)
      if (include && !directory) sourceFiles++
      return include
    },
  })
  for (const file of ['public', 'db', 'ops', 'vendor', 'package-lock.json', 'postcss.config.mjs', 'eslint.config.mjs', 'next-env.d.ts', '.env.example']) {
    if (await exists(join(root, file))) await cp(join(root, file), join(output, file), { recursive: true })
  }
  await cp(join(root, 'next.config.ts'), join(output, 'next.base.config.ts'))
  await writeFile(join(output, 'next.config.ts'), `import type { NextConfig } from 'next'\nimport base from './next.base.config'\n\n/** Bound compiler resolution and filesystem tracing to this assembled application. */\nconst config: NextConfig = { ...base, turbopack: { ...base.turbopack, root: process.cwd() }, outputFileTracingRoot: process.cwd() }\nexport default config\n`)
  const packageData = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))
  const runtimeScripts = ['dev', 'build', 'start', 'lint', 'typecheck', 'db:migrate', 'backup', 'backup:check', 'backup:status', 'automation:worker', 'mcp', 'user:reset-password', 'user:reset-mfa']
  if (ids.has('ESIGN')) runtimeScripts.push('esign:sync')
  packageData.scripts = Object.fromEntries(runtimeScripts.filter(name => packageData.scripts[name]).map(name => [name, packageData.scripts[name]]))
  await writeFile(join(output, 'package.json'), JSON.stringify(packageData, null, 2) + '\n')
  const config = JSON.parse(await readFile(join(root, 'tsconfig.json'), 'utf8'))
  config.include = ['next-env.d.ts', 'src/**/*.ts', 'src/**/*.tsx', '.next/types/**/*.ts', '.next/dev/types/**/*.ts']
  config.exclude = ['node_modules']
  await writeFile(join(output, 'tsconfig.json'), JSON.stringify(config, null, 2) + '\n')
  await mkdir(join(output, 'scripts'))
  for (const file of ['dotenv.ts', 'migrate.ts', 'backup.sh', 'restore-check.ts', 'backup-status.ts', 'automation-worker.ts', 'mcp.ts', 'reset-password.ts', 'reset-mfa.ts', ...(ids.has('ESIGN') ? ['esign-sync.ts'] : [])]) {
    await cp(join(root, 'scripts', file), join(output, 'scripts', file))
  }
  for (const [file, contents] of Object.entries(composition(selected))) await writeFile(join(output, 'src', 'assembly', file), contents)
  const excluded: ModuleExclusion[] = addonCatalog.filter(manifest => !ids.has(manifest.id)).map(manifest => ({
    id: manifest.id,
    paths: [...manifest.seats.map(seat => `/ledger/:ledgerId${seat}`), ...manifest.routes ?? []],
    tables: [...new Set([...(manifest.backup?.companyData?.map(item => item.table) ?? []), ...Object.keys(manifest.backup?.excluded ?? {})])].filter(table => !manifest.referenceTables?.includes(table)),
  }))
  await writeFile(join(output, 'src', 'assembly', 'excluded.ts'), `import type { ModuleExclusion } from '@/lib/module-contract'\nexport const excludedModules: readonly ModuleExclusion[] = ${JSON.stringify(excluded, null, 2)}\n`)
  await writeFile(join(output, 'figtree-assembly.json'), JSON.stringify({ format: 1, version: packageData.version, base: BASE_MODULES, addons: selected.map(manifest => manifest.id), sourceFiles }, null, 2) + '\n')
  await writeFile(join(output, 'README.md'), `# Banyan assembled application\n\nVersion: ${packageData.version}. Add-ons: ${selected.map(manifest => manifest.id).join(', ') || 'none'}.\n\nInstall dependencies with npm ci. Copy .env.example to .env.local and configure this deployment. Run npm run db:migrate -- --database <exact verified database name>, npm run build, then npm start. Historical migrations retain all legacy tables; module selection controls the assembled application.\n\nThis directory contains no source workspace credentials, attachment stores, Git history, or agent sessions.\n`)
  return { output, modules: selected.map(manifest => manifest.id), sourceFiles }
}

export async function buildAssembly(output: string, root = process.cwd()) {
  if (!await exists(join(output, 'figtree-assembly.json'))) throw new Error('Build only an assembled application directory.')
  if (!process.env.DATABASE_URL) throw new Error('Set DATABASE_URL explicitly before building the assembled application.')
  if (!await exists(join(output, 'node_modules'))) {
    const staging = await mkdtemp(join(output, '.dependencies-'))
    try {
      await cp(join(root, 'node_modules'), join(staging, 'node_modules'), {
        recursive: true, mode: constants.COPYFILE_FICLONE, verbatimSymlinks: true,
        filter: path => basename(path) !== '.DS_Store',
      })
      await rename(join(staging, 'node_modules'), join(output, 'node_modules'))
    } finally { await rm(staging, { recursive: true, force: true }) }
  }
  await new Promise<void>((accept, reject) => {
    const child = spawn(process.execPath, [join(output, 'node_modules/next/dist/bin/next'), 'build'], {
      cwd: output, env: { ...process.env, NODE_ENV: 'production', NODE_OPTIONS: '', NEXT_TELEMETRY_DISABLED: '1' }, stdio: 'inherit',
    })
    child.once('error', reject)
    child.once('exit', code => code === 0 ? accept() : reject(new Error(`Assembled build exited ${code}.`)))
  })
}
